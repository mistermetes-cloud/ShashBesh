import { openTechnical } from './support';
import { readFileSync } from 'node:fs';
import { test, expect } from '@playwright/test';
import { engine } from '../helpers';
import { simulate } from '../../packages/tournament/src/index';
import { exportLog } from '../../packages/engine/src/index';
test('manual game, mobile board, AI controls, export and imported victory replay', async ({ page }) => {
    test.setTimeout(180000);
    const errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('/');
    await openTechnical(page);
    await expect(page.locator('[data-cell]')).toHaveCount(64);
    await page.getByLabel('Seed (необязательно)').fill('browser-v1');
    for (const p of [1, 2, 3, 4])
        await page.getByLabel(`Игрок P${p}`, { exact: true }).selectOption('human');
    await page.getByRole('button', { name: 'Начать новую партию' }).click();
    for (let i = 0; i < 8 && await page.getByRole('button', { name: 'Бросить жребий' }).isVisible(); i++)
        await page.getByRole('button', { name: 'Бросить жребий' }).click();
    await expect(page.getByRole('button', { name: 'Бросить кубики' })).toBeEnabled();
    await page.getByRole('button', { name: 'Бросить кубики' }).click();
    await expect(page.getByRole('button', { name: 'Бросить кубики' })).toBeDisabled();
    for (let roll = 0; roll < 12; roll++) {
        const moves = page.locator('.move-list button');
        if (await moves.count() > 0) {
            await expect(page.getByRole('button', { name: 'Завершить бросок' })).toBeDisabled();
            await moves.first().click();
            break;
        }
        await page.getByRole('button', { name: 'Завершить бросок' }).click();
        await page.getByRole('button', { name: 'Бросить кубики' }).click();
    }
    await expect(page.locator('.piece')).not.toHaveCount(0);
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Экспорт журнала' }).click();
    const download = await downloadPromise;
    expect(download.suggestedFilename()).toBe('shashbesh-replay.jsonl');
    const journal = readFileSync((await download.path())!, 'utf8').trim().split('\n').map(line => JSON.parse(line));
    expect(journal.every(e => e.journalVersion === 2 && e.timestamp && e.eventId && e.timeSource === 'wall')).toBe(true);
    const dataPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Экспорт данных ИИ' }).click();
    const data = await dataPromise;
    expect(data.suggestedFilename()).toBe('shashbesh-dataset.jsonl');
    const records = readFileSync((await data.path())!, 'utf8').trim().split('\n').map(line => JSON.parse(line));
    expect(records.length).toBeGreaterThan(0);
    expect(records.every(r => r.controller.kind === 'human' && r.result.reward === null)).toBe(true);
    expect(records.some(r => r.selectedAction && r.before.pieces.some((p: any) => p.status === 'reserve') && r.after.pieces.some((p: any) => p.status === 'track'))).toBe(true);
    const anchorPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Контрольный хеш' }).click();
    const anchor = JSON.parse(readFileSync((await (await anchorPromise).path())!, 'utf8'));
    expect(anchor.headHash).toBe(journal.at(-1).hash);
    expect(anchor.eventCount).toBe(journal.length);
    const replay = exportLog(simulate(engine, 'browser-replay', ['greedy', 'tactical']).state);
    await page.locator('input[type=file]').setInputFiles({ name: 'game.jsonl', mimeType: 'application/x-ndjson', buffer: Buffer.from(replay) });
    await expect(page.locator('h2')).toContainText('Победа');
    await expect(page.locator('[data-cell]')).toHaveCount(64);
    const slider = page.locator('input[type=range]');
    await slider.fill('0');
    await expect(page.locator('h2')).toHaveText('Начальный жребий');
    await slider.fill(await slider.getAttribute('max') || '0');
    await expect(page.locator('h2')).toContainText('Победа');
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.locator('[data-cell]')).toHaveCount(64);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
    await page.getByRole('button', { name: 'Вернуться к игре' }).click();
    await page.getByLabel('Игрок P1', { exact: true }).selectOption('ai-v0.1');
    await page.getByLabel('Игрок P2', { exact: true }).selectOption('tactical');
    await page.getByLabel('Игрок P3', { exact: true }).selectOption('tactical');
    await page.getByLabel('Игрок P4', { exact: true }).selectOption('tactical');
    await page.getByLabel('Игроков', { exact: true }).selectOption('2');
    await page.getByRole('button', { name: 'Начать новую партию' }).click();
    await page.getByLabel('Скорость ботов').selectOption('175');
    await page.getByRole('button', { name: 'Запустить ботов' }).click();
    await expect(page.locator('.piece')).not.toHaveCount(0, { timeout: 15000 });
    await page.getByRole('button', { name: 'Пауза', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Запустить ботов' })).toBeVisible();
    await page.getByRole('button', { name: 'Запустить ботов' }).click();
    await page.clock.install({time:new Date('2026-10-11T13:00:00Z')});
    await page.clock.pauseAt(new Date('2026-10-11T13:01:00Z'));
    // Execute every real animated command with controlled timers; do not wait several minutes for FAST's deliberate delays.
    for(let i=0;i<20&&!(await page.locator('h2').innerText()).includes('Победа');i++)await page.clock.runFor(20000);
    await expect(page.locator('h2')).toContainText('Победа');
    const neuralExport = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Экспорт данных ИИ' }).click();
    const neuralData = await neuralExport;
    const learned = readFileSync((await neuralData.path())!, 'utf8').trim().split('\n').map(line => JSON.parse(line));
    expect(learned.some(r => r.controller.id === 'ai-v0.1' && r.controller.version === 'ShashBesh AI v0.1')).toBe(true);
    await page.getByRole('button', { name: 'Наблюдать AI vs AI' }).click();
    await page.clock.runFor(1);
    await expect(page.getByRole('region',{name:'Режим наблюдения'})).toBeVisible();
    await page.getByRole('button', { name: 'Пауза', exact: true }).click();
    expect(errors).toEqual([]);
});

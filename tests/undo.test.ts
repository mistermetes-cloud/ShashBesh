import { test } from 'node:test';
import assert from 'node:assert/strict';
import { engine, ready, track } from './helpers';
import { stateHash, canonical, actionHistory, activeEvents } from '../packages/engine/src/index';
import { decisions } from '../packages/training/src/index';
const who = { kind: 'human' as const, id: 'human-1', version: null };
test('Human undo restores capture, points and dice and preserves all historical events', () => {
    let s = engine.finishRoll(engine.roll(ready(), [2, 3]), who);
    const p2 = { ...who, id: 'human-2' };
    s = engine.roll(s, [6, 6]);
    s = engine.applySequence(s, engine.legalSequencesForRoll(s).find(seq => seq.every(a => a.pieceId === 'P2-1'))!, p2);
    s = engine.finishRoll(s, p2);
    s = engine.roll(s, [6, 6]);
    s = engine.applySequence(s, engine.legalSequencesForRoll(s).find(seq => seq.slice(0, 3).every(a => a.pieceId === 'P2-1') && seq[3].pieceId === 'P2-2' && seq[3].kind === 'deploy')!, p2);
    s = engine.finishRoll(s, p2);
    s = engine.roll(s, [2, 3]);
    s = engine.applySequence(s, engine.legalSequencesForRoll(s).find(seq => seq.every(a => a.pieceId === 'P2-2'))!, p2);
    s = engine.finishRoll(s, p2);
    s = engine.roll(s, [6, 3]);
    const before = s, action = engine.legalActions(s).find(a => a.kind === 'deploy')!;
    s = engine.applyAction(s, action, who);
    const old = [...s.eventLog];
    s = engine.undoAction(s, 1, who);
    const { eventLog: _, ...restored } = s, { eventLog: __, ...expected } = before;
    assert.deepEqual(restored, expected);
    assert.deepEqual(s.eventLog.slice(0, old.length), old);
    assert.equal(s.eventLog.at(-1)!.type, 'undo_action');
    assert.deepEqual(engine.replay(s.eventLog), s);
    assert.ok(Array.from(decisions(engine, s.eventLog)).every(r => r.eventSeq !== [...old].reverse().find(e => e.type === 'action')!.seq));
    const rows = actionHistory(engine, s.eventLog);
    assert.equal(rows.at(-1)!.undone, true);
    assert.equal(rows.at(-1)!.action.captureIds[0], 'P2-1');
});
test('Undo across an extra actual throw reuses observed dice without requesting new randomness', () => {
    let s = engine.roll(ready(), [6, 6]);
    s = engine.applySequence(s, engine.legalSequencesForRoll(s)[0], who);
    s = engine.finishRoll(s, who);
    s = engine.roll(s, [5, 6]);
    s = engine.undoAction(s, 1, who);
    assert.deepEqual(s.currentRoll?.dice, [6, 6]);
    assert.equal(s.currentRoll?.remainingActions.length, 1);
    assert.deepEqual(s.pendingRolls?.[0].dice, [5, 6]);
    s = engine.applySequence(s, engine.legalSequencesForRoll(s)[0], who);
    s = engine.finishRoll(s, who);
    assert.throws(() => engine.roll(s, [1, 1]));
    s = engine.roll(s, [5, 6]);
    assert.equal((s.eventLog.at(-1)!.payload as any).reusedFrom !== undefined, true);
    assert.equal(s.pendingRolls, undefined);
    assert.deepEqual(engine.replay(s.eventLog), s);
});
test('Agent, foreign human and handed-off turn cannot be undone; history never changes live state', () => {
    let s = engine.roll(ready(), [6, 3]);
    s = engine.applySequence(s, engine.legalSequencesForRoll(s)[0], who);
    assert.equal(engine.undoTarget(s, 1, { ...who, id: 'other' }), null);
    assert.equal(engine.undoTarget(s, 1, { kind: 'agent', id: 'ai', version: 'v' }), null);
    const hash = stateHash(s);
    const rows = actionHistory(engine, s.eventLog);
    assert.ok(rows.length);
    assert.equal(stateHash(s), hash);
    s = engine.finishRoll(s, who);
    assert.throws(() => engine.undoAction(s, 1, who));
});

test('Training decision has before/after, exact mask, actor, dice, captures and anonymous identity', () => {
    let s = engine.roll(ready(), [6, 3]);
    const who: ControllerIdentity = { kind: 'human', id: 'local-P1', version: null };
    s = engine.applyAction(s, engine.legalActions(s)[0], who);
    const records = Array.from(decisions(engine, s.eventLog, { controllers: { 1: who, 2: { ...who, id: 'local-P2' } } }));
    assert.equal(records.length, 1);
    const r = records[0];
    assert.equal(r.actor, 1);
    assert.deepEqual(r.dice, [6, 3]);
    assert.equal(r.controller.id, 'local-P1');
    assert.equal(r.mode, 'human-human');
    assert.equal(r.before.pieces[0].status, 'reserve');
    assert.equal(r.after.pieces[0].status, 'track');
    assert.ok(r.legalActions.some(a => canonical(a) === canonical(r.selectedAction)));
    assert.equal(r.result.reward, null);
    assert.equal(r.result.status, 'unfinished');
    const x = encode(r, engine.geometry);
    assert.equal(x.pieces.length, 20);
    assert.ok(x.pieces.every(row => row.length === 73));
    assert.deepEqual(x.playerMask, [1, 1, 0, 0]);
    assert.ok(x.chosenIndex >= 0);
    assert.equal(x.valueTarget, null);
    assert.equal('after' in x, false);
    assert.equal('winner' in x, false);
    assert.equal('seedMetadata' in r.before, false);
    assert.throws(() => encode(r, { ...engine.geometry, corners: [] }));
});
test('Completed self-play data labels both sides, derives captures and verified final state', () => {
    const game = simulate(engine, 'training-self-play', ['greedy', 'greedy']);
    const records = Array.from(decisions(engine, game.state.eventLog));
    assert.ok(records.length > 0);
    assert.ok(records.every(r => r.mode === 'self-play' && r.controller.kind === 'agent'));
    assert.ok(records.some(r => r.result.actorOutcome === 'win'));
    assert.ok(records.some(r => r.result.actorOutcome === 'loss'));
    const captures = records.flatMap(r => r.captures);
    assert.equal(captures.length, game.captures);
    assert.ok(captures.every(c => c.after.status === 'reserve' && c.after.outerSteps === 0));
    assert.equal(records.at(-1)!.after.winner, game.winner);
    assert.equal(stateHash(engine.replay(game.state.eventLog)), game.stateHash);
    assert.equal(split(game.state.gameId), split(game.state.gameId));
    assert.ok(['train', 'validation', 'test'].includes(split(game.state.gameId)));
});
test('All four learning modes and legacy unknown identities remain explicit', () => {
    const human: ControllerIdentity = { kind: 'human', id: 'session-player', version: null }, agent: ControllerIdentity = { kind: 'agent', id: 'greedy', version: 'baseline-v1' };
    const combinations = [{ map: { 1: human, 2: human }, mode: 'human-human' }, { map: { 1: human, 2: agent }, mode: 'human-ai' }, { map: { 1: agent, 2: { ...agent, id: 'tactical' } }, mode: 'ai-ai' }, { map: { 1: agent, 2: agent }, mode: 'self-play' }];
    for (const { map, mode } of combinations) {
        let s = engine.roll(ready(), [6, 3]);
        s = engine.applyAction(s, engine.legalActions(s)[0], map[1]);
        assert.equal(Array.from(decisions(engine, s.eventLog, { controllers: map }))[0].mode, mode);
    }
    let s = engine.roll(ready(), [6, 3]);
    s = engine.applyAction(s, engine.legalActions(s)[0]);
    assert.equal(Array.from(decisions(engine, s.eventLog))[0].controller.kind, 'unknown');
    const bad = structuredClone(s.eventLog);
    bad.at(-1)!.hash = 'bad';
    assert.throws(() => Array.from(decisions(engine, bad)));
});
test('Forced pass is a recorded decision, with an explicit pass candidate for a neural policy', () => {
    let s = engine.roll(ready(), [2, 3]);
    const human: ControllerIdentity = { kind: 'human', id: 'pass-human', version: null };
    s = engine.finishRoll(s, human);
    const records = Array.from(decisions(engine, s.eventLog, { controllers: { 1: human, 2: human } }));
    assert.equal(records.length, 1);
    const r = records[0];
    assert.equal(r.decisionKind, 'pass');
    assert.equal(r.selectedAction, null);
    assert.deepEqual(r.legalActions, []);
    assert.equal(r.before.activePlayer, 1);
    assert.equal(r.after.activePlayer, 2);
    assert.equal(r.controller.id, 'pass-human');
    const x = encode(r, engine.geometry);
    assert.equal(x.chosenIndex, 0);
    assert.equal(x.candidates.length, 1);
    assert.deepEqual(x.candidates[0].slice(0, 4), [-1, 3, 0, -1]);
});
